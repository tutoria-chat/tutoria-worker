class ListQuizzesResponse(BaseModel):
    quizzes: List[dict]
    total: int
    course_id: int


@router.get("/{course_id}/quizzes", response_model=ListQuizzesResponse)
async def list_course_quizzes(
    course_id: int,
    difficulty: Optional[str] = None,
    source: Optional[str] = None,
    module_id: Optional[int] = None,
    db: Session = Depends(get_db),
    current_user=Depends(get_current_professor_or_super_admin),
):
    """
    List every quiz question in the course's question bank.

    Optional filters:
    - difficulty: easy, medium, hard
    - source: ai_generated, uploaded, manual
    - module_id: only questions generated from that module's material
    """
    from app.models import Quiz

    course = db.query(CourseModel).filter(CourseModel.id == course_id).first()
    if not course:
        raise HTTPException(status_code=404, detail="Course not found")

    query = db.query(Quiz).filter(Quiz.course_id == course_id)

    if difficulty and difficulty in ("easy", "medium", "hard"):
        query = query.filter(Quiz.difficulty == difficulty)

    if source and source in ("ai_generated", "uploaded", "manual"):
        query = query.filter(Quiz.source == source)

    if module_id:
        query = query.filter(Quiz.module_id == module_id)

    quizzes = query.order_by(Quiz.question_number).all()

    return ListQuizzesResponse(
        quizzes=[q.to_dict() for q in quizzes],
        total=len(quizzes),
        course_id=course_id
    )


@router.delete("/{course_id}/quizzes/{quiz_id}")
async def delete_quiz_question(
    course_id: int,
    quiz_id: int,
    db: Session = Depends(get_db),
    current_user=Depends(get_current_professor_or_super_admin),
):
    """
    Delete a single quiz question from the course's question bank.
    """
    from app.models import Quiz

    course = db.query(CourseModel).filter(CourseModel.id == course_id).first()
    if not course:
        raise HTTPException(status_code=404, detail="Course not found")

    quiz = db.query(Quiz).filter(Quiz.id == quiz_id, Quiz.course_id == course_id).first()
    if not quiz:
        raise HTTPException(status_code=404, detail="Quiz question not found")

    db.delete(quiz)
    db.commit()

    return {"status": "success", "message": "Quiz question deleted"}
