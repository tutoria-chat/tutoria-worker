"""
Course-scoped management endpoints.

The question bank ("banco de questoes") belongs to the course: every question a
professor uploads, reviews or deletes here is visible to every student in the
course, whichever module they entered the widget from. Questions generated by AI
still record the module their material came from (Quiz.module_id), but that is
provenance only - never a scope.
"""
from fastapi import APIRouter, Depends, HTTPException, UploadFile, File as FastAPIFile
from sqlalchemy.orm import Session
from pydantic import BaseModel
from typing import List, Optional
import logging

from app.core.database import get_db
from app.core.config import settings
from app.core.super_admin_auth import get_current_professor_or_super_admin
from app.models import Course as CourseModel

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/v2/courses", tags=["courses"])


