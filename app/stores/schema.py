"""
The Postgres tables that replace DynamoDB and SQS (docs/MULTICLOUD.md).

  "ChatHistory"         the DynamoDB ChatMessages table (CHAT_STORE=postgres)
  "QuizAttemptAnswers"  the DynamoDB QuizAttempts table (CHAT_STORE=postgres)
  "WorkerJobs"          the SQS queues to tutoria-worker (JOB_QUEUE=postgres)

They are shared: tutoria-api writes chat and quiz answers, tutoria-worker
writes feedback chat rows and reads both for analytics, TutoriaApi reads chat
for the dashboards, and all three put jobs in "WorkerJobs". So every service
that uses them runs this same DDL at startup: CREATE ... IF NOT EXISTS under
one advisory lock (several tasks starting at once wait for each other). The
copies in tutoria-worker (app/stores/schema.py) and TutoriaApi (PostgresStores
.cs) must stay identical to this one.

DynamoDB's 90-day TTL becomes "ExpiresAt": reads skip expired rows and
cleanup_expired() deletes them in small batches (tutoria-api runs it).
"""

import logging

from sqlalchemy import text

logger = logging.getLogger(__name__)

# Shared with tutoria-worker and TutoriaApi: the same id in all three.
SCHEMA_LOCK = 734_331_001
_CLEANUP_LOCK = 734_331_002

_CLEANUP_BATCH = 5_000
_CLEANUP_MAX_BATCHES = 20

DDL = (
    """
    CREATE TABLE IF NOT EXISTS "ChatHistory" (
        "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "ConversationId" varchar(200) NOT NULL,
        "Ts"             bigint       NOT NULL,
        "MessageId"      varchar(64)  NOT NULL,
        "StudentId"      integer      NOT NULL DEFAULT 0,
        "ModuleId"       integer      NOT NULL DEFAULT 0,
        "Question"       text         NOT NULL DEFAULT '',
        "Response"       text         NOT NULL DEFAULT '',
        "ModelUsed"      varchar(200),
        "Provider"       varchar(100),
        "HasFile"        boolean      NOT NULL DEFAULT false,
        "FileName"       varchar(500),
        "TokenCount"     integer,
        "ResponseTime"   integer,
        "Matricula"      varchar(100),
        "CreatedAt"      timestamptz  NOT NULL DEFAULT now(),
        "ExpiresAt"      timestamptz  NOT NULL
    )
    """,
    'CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Conversation" ON "ChatHistory" ("ConversationId", "Ts")',
    'CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Student" ON "ChatHistory" ("StudentId", "Ts")',
    'CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Module" ON "ChatHistory" ("ModuleId", "Ts")',
    'CREATE INDEX IF NOT EXISTS "IX_ChatHistory_Provider" ON "ChatHistory" ("Provider", "Ts")',
    'CREATE INDEX IF NOT EXISTS "IX_ChatHistory_ExpiresAt" ON "ChatHistory" ("ExpiresAt")',
    """
    CREATE TABLE IF NOT EXISTS "QuizAttemptAnswers" (
        "Id"              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "AttemptId"       varchar(64)  NOT NULL,
        "ModuleId"        integer      NOT NULL,
        "Ts"              bigint       NOT NULL,
        "StudentId"       integer      NOT NULL DEFAULT 0,
        "QuizId"          integer,
        "QuestionNumber"  integer      NOT NULL DEFAULT 0,
        "SelectedAnswer"  text         NOT NULL DEFAULT '',
        "CorrectAnswer"   text         NOT NULL DEFAULT '',
        "IsCorrect"       boolean      NOT NULL DEFAULT false,
        "ConceptsCovered" text         NOT NULL DEFAULT '',
        "Difficulty"      varchar(30)  NOT NULL DEFAULT 'medium',
        "CreatedAt"       timestamptz  NOT NULL DEFAULT now(),
        "ExpiresAt"       timestamptz  NOT NULL
    )
    """,
    'CREATE INDEX IF NOT EXISTS "IX_QuizAttemptAnswers_Student" ON "QuizAttemptAnswers" ("StudentId", "Ts")',
    'CREATE INDEX IF NOT EXISTS "IX_QuizAttemptAnswers_Module" ON "QuizAttemptAnswers" ("ModuleId", "Ts")',
    'CREATE INDEX IF NOT EXISTS "IX_QuizAttemptAnswers_ExpiresAt" ON "QuizAttemptAnswers" ("ExpiresAt")',
    # One row per job. "Kind" names the old queue (extraction, quiz_gen,
    # transcription, grading, quiz_upload, feedback) and "Payload" is the same
    # JSON the SQS message carried. "State": queued -> processing -> done, or
    # back to queued with a later "AvailableAt" on failure, and failed after
    # the last attempt (the DLQ). The worker sets "Payload" to NULL when a job
    # ends either way: a feedback payload can carry the student's learning
    # note, which must never be kept (it was transient on SQS too).
    """
    CREATE TABLE IF NOT EXISTS "WorkerJobs" (
        "Id"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "Kind"        varchar(30)  NOT NULL,
        "Payload"     text,
        "State"       varchar(20)  NOT NULL DEFAULT 'queued',
        "Attempts"    integer      NOT NULL DEFAULT 0,
        "AvailableAt" timestamptz  NOT NULL DEFAULT now(),
        "CreatedAt"   timestamptz  NOT NULL DEFAULT now(),
        "ClaimedBy"   varchar(100),
        "ClaimedAt"   timestamptz,
        "LeaseUntil"  timestamptz,
        "FinishedAt"  timestamptz,
        "LastError"   varchar(1000)
    )
    """,
    # The claim query and the KEDA scaler both look only at waiting rows.
    'CREATE INDEX IF NOT EXISTS "IX_WorkerJobs_Waiting" ON "WorkerJobs" ("AvailableAt") '
    "WHERE \"State\" IN ('queued', 'processing')",
    'CREATE INDEX IF NOT EXISTS "IX_WorkerJobs_Finished" ON "WorkerJobs" ("FinishedAt") '
    "WHERE \"FinishedAt\" IS NOT NULL",
)

# Expired rows go; finished jobs are kept 14 days for diagnosis.
_CLEANUP = (
    ('"ChatHistory"', '"ExpiresAt" < now()'),
    ('"QuizAttemptAnswers"', '"ExpiresAt" < now()'),
    ('"WorkerJobs"', "\"FinishedAt\" < now() - interval '14 days'"),
)


def ensure_schema(engine) -> None:
    """Create whatever is missing; a no-op once everything exists."""
    with engine.begin() as conn:
        conn.execute(text("SELECT pg_advisory_xact_lock(:k)"), {"k": SCHEMA_LOCK})
        for statement in DDL:
            conn.execute(text(statement))
    logger.info("Postgres stores ready: ChatHistory, QuizAttemptAnswers, WorkerJobs")


def cleanup_expired(engine) -> int | None:
    """Delete expired rows a batch at a time. None when another task holds the lock."""
    deleted = 0
    with engine.connect() as conn:
        got = conn.execute(text("SELECT pg_try_advisory_lock(:k)"), {"k": _CLEANUP_LOCK}).scalar()
        conn.commit()
        if not got:
            return None
        try:
            for table, condition in _CLEANUP:
                for _ in range(_CLEANUP_MAX_BATCHES):
                    result = conn.execute(text(
                        f"DELETE FROM {table} WHERE ctid IN "  # noqa: S608 — constants only
                        f"(SELECT ctid FROM {table} WHERE {condition} LIMIT {_CLEANUP_BATCH})"
                    ))
                    conn.commit()
                    deleted += result.rowcount or 0
                    if (result.rowcount or 0) < _CLEANUP_BATCH:
                        break
        finally:
            conn.rollback()
            conn.execute(text("SELECT pg_advisory_unlock(:k)"), {"k": _CLEANUP_LOCK})
            conn.commit()
    if deleted:
        logger.info("Postgres stores: %d expired rows deleted", deleted)
    return deleted
